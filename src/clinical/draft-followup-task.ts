import { createHash } from "node:crypto";

export type DraftFollowupTaskInput = {
  patientId: string;
  resultReference: string;
  resultDisplay: string;
  resultDate: string;
  resultValue?: string;
  closureStatus: "OPEN_LOOP" | "CLOSED" | "INSUFFICIENT_EVIDENCE";
  priority?: "routine" | "urgent" | "asap" | "stat";
  planDescription: string;
  closureArtifact: Record<string, unknown>;
  authoredOn?: string;
};

export type DraftFollowupTaskOutput = {
  status: "draft_resources_created" | "not_created";
  closureArtifactHash: string;
  task?: Record<string, unknown>;
  auditEvent?: Record<string, unknown>;
  safetyNote: string;
};

export function draftFollowupTaskResource(
  input: DraftFollowupTaskInput,
): DraftFollowupTaskOutput {
  const closureArtifactHash = sha256CanonicalJson(input.closureArtifact);

  if (input.closureStatus !== "OPEN_LOOP") {
    return {
      status: "not_created",
      closureArtifactHash,
      safetyNote:
        "No draft Task was created because this result was not classified as an open loop. Clinician verification is still required.",
    };
  }

  const authoredOn = input.authoredOn ?? new Date().toISOString();
  const taskId = `resultloop-task-${closureArtifactHash.slice(0, 16)}`;
  const auditEventId = `resultloop-audit-${closureArtifactHash.slice(0, 16)}`;
  const priority = input.priority ?? "urgent";

  const task = {
    resourceType: "Task",
    id: taskId,
    status: "draft",
    intent: "proposal",
    priority,
    code: {
      text: "Abnormal result follow-up review",
    },
    description: input.planDescription,
    focus: {
      reference: input.resultReference,
      display: input.resultDisplay,
    },
    for: {
      reference: `Patient/${input.patientId}`,
    },
    authoredOn,
    lastModified: authoredOn,
    requester: {
      display: "ResultLoop MCP",
    },
    reasonReference: {
      reference: input.resultReference,
      display: `${input.resultDisplay}${input.resultValue ? `: ${input.resultValue}` : ""}`,
    },
    note: [
      {
        time: authoredOn,
        text:
          "Draft-only follow-up task generated by ResultLoop for clinician review. ResultLoop does not place orders, contact patients, or write to the FHIR server.",
      },
    ],
  };

  const auditEvent = {
    resourceType: "AuditEvent",
    id: auditEventId,
    type: {
      system: "http://terminology.hl7.org/CodeSystem/audit-event-type",
      code: "rest",
      display: "RESTful Operation",
    },
    subtype: [
      {
        system: "http://hl7.org/fhir/restful-interaction",
        code: "create",
        display: "create",
      },
    ],
    action: "E",
    recorded: authoredOn,
    outcome: "0",
    agent: [
      {
        who: {
          display: "ResultLoop MCP",
        },
        requestor: true,
      },
    ],
    source: {
      observer: {
        display: "ResultLoop MCP",
      },
    },
    entity: [
      {
        what: {
          identifier: {
            system: "urn:ietf:rfc:3986",
            value: `urn:sha-256:${closureArtifactHash}`,
          },
          display: "SHA-256 closure artifact hash",
        },
        role: {
          system: "http://terminology.hl7.org/CodeSystem/object-role",
          code: "20",
          display: "Job",
        },
      },
      {
        what: {
          reference: input.resultReference,
          display: input.resultDisplay,
        },
      },
    ],
  };

  return {
    status: "draft_resources_created",
    closureArtifactHash,
    task,
    auditEvent,
    safetyNote:
      "Draft resources only. ResultLoop did not POST, PUT, DELETE, order care, or contact the patient. A clinician must verify before any action.",
  };
}

export function sha256CanonicalJson(value: unknown): string {
  return createHash("sha256").update(canonicalize(value)).digest("hex");
}

function canonicalize(value: unknown): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }

  if (Array.isArray(value)) {
    return `[${value.map((item) => canonicalize(item)).join(",")}]`;
  }

  const object = value as Record<string, unknown>;
  return `{${Object.keys(object)
    .sort()
    .map((key) => `${JSON.stringify(key)}:${canonicalize(object[key])}`)
    .join(",")}}`;
}
