import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { Request } from "express";
import { IMcpTool } from "../tools/IMcpTool.js";
import { z } from "zod";
import { FhirUtilities } from "../fhir/fhir-utilities.js";
import { McpUtilities } from "../util/mcp-utilities.js";
import { logger } from "../util/logger.js";

/**
 * Tool 3: generate_result_closure_summary
 *
 * Generates a structured clinical safety audit artifact from the abnormal
 * result scan and follow-up context. This artifact is designed to be
 * reviewed by a clinician — ResultLoop never diagnoses or orders care.
 *
 * Output follows a "clinical safety worklist item" format:
 * - Abnormal result summary
 * - Closure evidence matrix
 * - Risk assessment
 * - Draft follow-up tasks
 * - Human review requirement
 * - Safety boundaries
 */
class GenerateResultClosureSummaryTool implements IMcpTool {
  registerTool(server: McpServer, req: Request) {
    server.registerTool(
      "generate_result_closure_summary",
      {
        description:
          "Generates a structured follow-up closure audit report for an abnormal " +
          "result. Combines the abnormal result details and follow-up context into " +
          "a clinical safety artifact with risk assessment, evidence matrix, and " +
          "draft follow-up tasks for clinician review. IMPORTANT: This tool " +
          "produces an audit report — it does NOT diagnose or order care.",
        inputSchema: {
          patientId: z
            .string()
            .describe(
              "The patient ID. Prompt Opinion patient context is authoritative when available.",
            ),
          resultReference: z
            .string()
            .describe(
              "The FHIR reference of the abnormal result (e.g., 'Observation/123').",
            ),
          resultDate: z.string().describe("The date of the abnormal result."),
          resultDisplay: z
            .string()
            .describe(
              "Display name of the abnormal result (e.g., 'Mammogram Screening').",
            ),
          resultValue: z
            .string()
            .describe("The value or conclusion of the abnormal result.")
            .optional(),
          closureStatus: z
            .enum(["OPEN_LOOP", "CLOSED"])
            .describe("The closure status from follow-up context check."),
          daysSinceResult: z
            .number()
            .describe("Days since the abnormal result was recorded."),
          totalFollowUpFound: z
            .number()
            .describe("Total number of follow-up evidence resources found."),
          evidenceChecked: z
            .string()
            .describe(
              "JSON string of the evidence checked array from follow-up context.",
            )
            .optional(),
        },
      },
      async ({
        patientId,
        resultReference,
        resultDate,
        resultDisplay,
        resultValue,
        closureStatus,
        daysSinceResult,
        totalFollowUpFound,
        evidenceChecked,
      }) => {
        try {
          patientId = FhirUtilities.getPatientIdOrThrow(req, patientId);

          logger.info(
            { patientId, resultReference, closureStatus },
            "Generating closure summary artifact",
          );

          let parsedEvidence: Array<{
            resourceType: string;
            found: number;
            references: string[];
          }> = [];

          if (evidenceChecked) {
            try {
              parsedEvidence = JSON.parse(evidenceChecked);
            } catch {
              logger.warn("Could not parse evidenceChecked JSON");
            }
          }

          // Build the structured closure artifact
          const artifact = {
            _resultLoopVersion: "0.1.0",
            _generatedAt: new Date().toISOString(),
            _disclaimer:
              "AUTOMATED AUDIT — This report is generated by ResultLoop for " +
              "clinician review. It does NOT constitute a diagnosis, treatment " +
              "recommendation, or clinical order. All findings require human " +
              "verification before any clinical action is taken.",

            closureStatus,
            followUpClosureRisk: closureStatus === "OPEN_LOOP" ? "HIGH" : "LOW",

            patient: {
              id: patientId,
            },

            abnormalResult: {
              reference: resultReference,
              date: resultDate,
              display: resultDisplay,
              value: resultValue || "See original result",
              daysSinceResult,
              urgencyNote:
                daysSinceResult > 30
                  ? `⚠️ OVERDUE: ${daysSinceResult} days since abnormal result with no documented follow-up`
                  : daysSinceResult > 14
                    ? `⚡ ATTENTION: ${daysSinceResult} days since abnormal result`
                    : `${daysSinceResult} days since abnormal result`,
            },

            closureEvidenceMatrix: {
              totalChecked: parsedEvidence.length || 5,
              totalFound: totalFollowUpFound,
              details:
                parsedEvidence.length > 0
                  ? parsedEvidence.map((e) => ({
                      resourceType: e.resourceType,
                      evidenceFound: e.found > 0,
                      count: e.found,
                      references: e.references,
                    }))
                  : [
                      {
                        resourceType: "ServiceRequest",
                        evidenceFound: false,
                        count: 0,
                        references: [],
                      },
                      {
                        resourceType: "Task",
                        evidenceFound: false,
                        count: 0,
                        references: [],
                      },
                      {
                        resourceType: "Communication",
                        evidenceFound: false,
                        count: 0,
                        references: [],
                      },
                      {
                        resourceType: "CarePlan",
                        evidenceFound: false,
                        count: 0,
                        references: [],
                      },
                      {
                        resourceType: "Encounter",
                        evidenceFound: false,
                        count: 0,
                        references: [],
                      },
                    ],
            },

            draftFollowUpTasks:
              closureStatus === "OPEN_LOOP"
                ? [
                    {
                      taskType: "review_abnormal_result",
                      priority: "urgent",
                      description: `Clinician review of abnormal result audit finding: ${resultDisplay} from ${resultDate}`,
                      assignTo: "ordering_clinician",
                      requiresHumanApproval: true,
                    },
                    {
                      taskType: "review_followup_plan",
                      priority: "urgent",
                      description: `Review whether a documented follow-up plan exists for: ${resultDisplay}`,
                      assignTo: "care_coordinator",
                      requiresHumanApproval: true,
                    },
                    {
                      taskType: "review_patient_communication_status",
                      priority: "high",
                      description: `Review whether patient communication is documented for: ${resultDisplay}`,
                      assignTo: "nursing_staff",
                      requiresHumanApproval: true,
                    },
                  ]
                : [],

            evidenceProvenance: {
              auditMethod:
                "FHIR R4 search per resource type with strict date-windowing and result linkage",
              linkageStrategy:
                "reasonReference → basedOn → focus → temporal proximity",
              dateWindow: {
                from: resultDate,
                to: new Date().toISOString().split("T")[0],
              },
              resourceTypesChecked: [
                "ServiceRequest",
                "Task",
                "Communication",
                "CarePlan",
                "Encounter",
              ],
              resourceTypesWithEvidence: parsedEvidence
                .filter((e) => e.found > 0)
                .map((e) => e.resourceType),
              citedEvidenceReferences: parsedEvidence
                .flatMap((e) => e.references)
                .filter((r) => r.length > 0),
              overallConfidence:
                parsedEvidence.length === 5
                  ? "HIGH"
                  : parsedEvidence.length > 0
                    ? "MEDIUM"
                    : "LOW",
              confidenceRationale:
                parsedEvidence.length === 5
                  ? `All 5 FHIR resource types searched; ${totalFollowUpFound} linked evidence item(s) found within strict date window.`
                  : "Partial evidence search; confidence reduced.",
            },

            clinicalSafetyContext: {
              citation:
                "35.5% of pulmonary nodule patients receive no follow-up imaging (AHRQ/Brigham & Women's, 2025). " +
                "26% of BI-RADS 3 findings have no documented closure (AHRQ Lacson, 2025). " +
                "Follow-up failure contributes to 46% of severe/fatal diagnostic adverse events (PMC, 2025). " +
                "Diagnostic errors cost $870 billion/year in the US (OECD, 2025).",
              impactStatement:
                closureStatus === "OPEN_LOOP"
                  ? "This open-loop abnormal result represents a potential patient " +
                    "safety risk and should be reviewed by a clinician."
                  : "Follow-up evidence has been documented for this result.",
            },

            safetyBoundaries: {
              resultLoopDoes: [
                "Audit structured FHIR data for follow-up evidence",
                "Flag abnormal results with no documented follow-up",
                "Generate draft tasks for clinician review",
                "Cite FHIR resource references for traceability",
              ],
              resultLoopDoesNot: [
                "Diagnose conditions",
                "Recommend treatments",
                "Order clinical actions",
                "Contact patients directly",
                "Replace clinical judgment",
              ],
              requiresHumanApproval: true,
            },
          };

          logger.info(
            {
              patientId,
              closureStatus,
              draftTasks: artifact.draftFollowUpTasks.length,
            },
            "Closure summary artifact generated",
          );

          return McpUtilities.createJsonResponse(artifact);
        } catch (error) {
          logger.error({ error }, "Failed to generate closure summary");
          return McpUtilities.createTextResponse(
            `Error generating closure summary: ${error instanceof Error ? error.message : "Unknown error"}`,
            { isError: true },
          );
        }
      },
    );
  }
}

export const GenerateResultClosureSummaryToolInstance =
  new GenerateResultClosureSummaryTool();
